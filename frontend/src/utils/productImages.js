/**
 * Get product image based on product data
 * @param {Object} product - Product object with image and category properties
 * @param {number} index - Index for fallback image selection (default: 0)
 * @returns {string|Object} Image URL or imported image object
 */
export const getProductImage = (product, index = 0) => {
    if (product.image) {
        // Check if image path exists in imageMap
        if (imageMap[product.image]) {
            return imageMap[product.image];
        }
        // If image is a URL, return it directly
        if (product.image.startsWith("http") || product.image.startsWith("/")) {
            return product.image;
        }
    }

    // Fallback to category-specific images
    if (product.category && categoryImages[product.category]) {
        const categoryImgs = categoryImages[product.category];
        if (categoryImgs.length > 0) {
            return categoryImgs[index % categoryImgs.length];
        }
    }

    // Final fallback to default product images
    return productImages[index % productImages.length];
};

